@app.route("/health")
def health() -> Response:
    """Readiness probe used by Cloudflare Containers and the Workflow.

    Returns a 200 response indicating the server is running and ready to
    accept video-processing requests. The Container runtime polls this
    endpoint during ``startAndWaitForPorts()`` to confirm Flask is serving
    before the Workflow sends actual work requests.

    Returns:
        A JSON response ``{"ok": true}`` with HTTP 200.
    """
    app.logger.debug("[health] GET /health → 200")
    return jsonify({"ok": True})


@app.route("/transcode", methods=["POST"])
def transcode() -> Response:
    """Transcode a video to H.264/AAC MP4 format.

    Downloads the input video from a presigned R2 GET URL, transcodes it
    to H.264 video with AAC audio in an MP4 container using libx264 and
    the aac encoder, then uploads the result to a presigned R2 PUT URL.

    This endpoint accepts any video format supported by ffmpeg as input.
    The output is always an MP4 file suitable for subsequent processing
    steps (/extract-audio and /grayscale).

    Request JSON:
        input_url (str): Presigned GET URL for the source video in R2
            (e.g. the original uploaded file at ``incoming/{videoId}.{ext}``).
        output_url (str): Presigned PUT URL for the transcoded MP4 in R2
            (e.g. ``video/{videoId}.mp4``).

    Returns:
        200 JSON ``{"ok": true, "duration_seconds": <float>}`` on success.
        500 JSON ``{"ok": false, "error": "...", "stderr": "..."}`` if
            ffmpeg exits with a non-zero return code (truncated to last
            2000 chars of stderr).
        504 JSON ``{"ok": false, "error": "ffmpeg timed out ..."}`` if
            the subprocess exceeds 1800 seconds.

    Example::

        POST /transcode
        Content-Type: application/json

        {"input_url": "https://r2.example.com/...", "output_url": "https://r2.example.com/..."}
    """
    app.logger.info("[transcode] POST /transcode received")
    return _run_ffmpeg_job(
        input_ext="input",
        output_ext="output.mp4",
        build_cmd=lambda inp, out: [
            "ffmpeg",
            "-i", inp,
            "-c:v", "libx264",
            "-c:a", "aac",
            "-y", out,
        ],
        output_content_type="video/mp4",
    )


@app.route("/extract-audio", methods=["POST"])
def extract_audio() -> Response:
    """Extract the audio track from a video as an MP3 file.

    Downloads a transcoded MP4 from a presigned R2 GET URL, strips the
    video stream entirely (``-vn``), re-encodes the audio with libmp3lame,
    and uploads the resulting MP3 to a presigned R2 PUT URL.

    This step runs after /transcode so the input is always an H.264/AAC
    MP4 with a guaranteed audio stream.

    Request JSON:
        input_url (str): Presigned GET URL for the transcoded MP4 in R2
            (e.g. ``video/{videoId}.mp4``).
        output_url (str): Presigned PUT URL for the extracted MP3 in R2
            (e.g. ``audio/{videoId}.mp3``).

    Returns:
        200 JSON ``{"ok": true, "duration_seconds": <float>}`` on success.
        500 JSON ``{"ok": false, "error": "...", "stderr": "..."}`` if
            ffmpeg exits with a non-zero return code.
        504 JSON ``{"ok": false, "error": "ffmpeg timed out ..."}`` if
            the subprocess exceeds 1800 seconds.

    Example::

        POST /extract-audio
        Content-Type: application/json

        {"input_url": "https://r2.example.com/...", "output_url": "https://r2.example.com/..."}
    """
    app.logger.info("[extract-audio] POST /extract-audio received")
    return _run_ffmpeg_job(
        input_ext="input",
        output_ext="output.mp3",
        build_cmd=lambda inp, out: [
            "ffmpeg",
            "-i", inp,
            "-vn",
            "-c:a", "libmp3lame",
            "-y", out,
        ],
        output_content_type="audio/mpeg",
        # Probe for audio before running ffmpeg. If the input has no audio
        # stream (video-only), skip gracefully instead of failing with exit
        # code 234 "Output file does not contain any stream".
        check_audio_stream=True,
    )


@app.route("/grayscale", methods=["POST"])
def grayscale() -> Response:
    """Apply a grayscale filter to a video, preserving the audio track.

    Downloads an MP4 from a presigned R2 GET URL, applies the
    ``format=gray`` video filter (which converts the YUV colour space to
    grayscale), copies the audio stream without re-encoding (``-c:a copy``),
    and uploads the result to a presigned R2 PUT URL.

    This is the final processing step before the video is uploaded to
    Cloudflare Stream. Copying audio avoids an unnecessary encode cycle
    since the audio track was already encoded by /transcode.

    Request JSON:
        input_url (str): Presigned GET URL for the transcoded MP4 in R2
            (e.g. ``video/{videoId}.mp4``).
        output_url (str): Presigned PUT URL for the grayscale MP4 in R2
            (e.g. ``bwvideo/{videoId}.mp4``).

    Returns:
        200 JSON ``{"ok": true, "duration_seconds": <float>}`` on success.
        500 JSON ``{"ok": false, "error": "...", "stderr": "..."}`` if
            ffmpeg exits with a non-zero return code.
        504 JSON ``{"ok": false, "error": "ffmpeg timed out ..."}`` if
            the subprocess exceeds 1800 seconds.

    Example::

        POST /grayscale
        Content-Type: application/json

        {"input_url": "https://r2.example.com/...", "output_url": "https://r2.example.com/..."}
    """
    app.logger.info("[grayscale] POST /grayscale received")
    return _run_ffmpeg_job(
        input_ext="input",
        output_ext="output.mp4",
        build_cmd=lambda inp, out: [
            "ffmpeg",
            "-i", inp,
            "-vf", "format=gray",
            "-c:a", "copy",
            "-y", out,
        ],
        output_content_type="video/mp4",
    )
