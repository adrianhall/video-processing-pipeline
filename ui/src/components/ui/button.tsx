/**
 * Accessible button component with variant and size support.
 *
 * Renders a `<button>` element (or any element via `asChild`) styled with
 * shadcn/ui's nova preset.  Supports six visual variants and seven size
 * tokens.  Aria attributes (`aria-invalid`, `aria-haspopup`) are reflected
 * as CSS-visible `data-` attributes so styles can respond without JavaScript.
 *
 * @param props - All standard `<button>` props plus:
 * @param props.variant - Visual style: `"default"` | `"outline"` | `"secondary"` |
 *   `"ghost"` | `"destructive"` | `"link"`.  Defaults to `"default"`.
 * @param props.size - Dimension token: `"default"` | `"xs"` | `"sm"` | `"lg"` |
 *   `"icon"` | `"icon-xs"` | `"icon-sm"` | `"icon-lg"`.  Defaults to `"default"`.
 * @param props.asChild - When `true`, merges props onto the immediate child
 *   element instead of rendering a `<button>`.  Use for `<a>` links that look
 *   like buttons.
 * @param props.className - Additional Tailwind classes merged via `cn()`.
 * @returns A styled button or the `asChild` element with button styles.
 *
 * @example
 * ```tsx
 * <Button variant="outline" size="sm" onClick={handleSave}>
 *   Save
 * </Button>
 *
 * // As a link
 * <Button asChild variant="link">
 *   <a href="/videos">View all videos</a>
 * </Button>
 * ```
 */
function Button({
  className,
  variant = "default",
  size = "default",
  asChild = false,
  ...props
}: React.ComponentProps<"button"> &
  VariantProps<typeof buttonVariants> & {
    asChild?: boolean;
  }) {
  const Comp = asChild ? Slot.Root : "button";

  return (
    <Comp
      data-slot="button"
      data-variant={variant}
      data-size={size}
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  );
}

export { Button, buttonVariants };
